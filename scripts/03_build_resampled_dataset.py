"""
Resamples raw per-timestep telemetry (irregular time steps) onto a fixed
5m distance grid for every clean_telemetry_lap in master_laps_metadata.csv,
engineers derived features, and applies the rule-based baseline state label.

Inputs:
  master_laps_metadata.csv (from 02_build_master_laps.py, in PROCESSED_DIR)
  {RACE_DIR}/{Driver}/{LapNumber}_tel.json  (raw TracingInsights telemetry,
  external to this project folder)
Output:
  resampled_telemetry.parquet - one row per (Driver, LapNumber, distance-grid-point)
  written to PROCESSED_DIR
"""
import json
import os
import numpy as np
import pandas as pd

PROJECT_DIR = "/Users/zhangyimeng/SportsAnalytics/f1"
PROCESSED_DIR = f"{PROJECT_DIR}/data/processed"
RACE_DIR = "/Users/zhangyimeng/SportsAnalytics/2026/Miami Grand Prix/Race"
GRID_STEP = 5.0

master = pd.read_csv(f"{PROCESSED_DIR}/master_laps_metadata.csv", index_col=0)
clean = master[master['clean_telemetry_lap']].copy()
clean['LapNumber'] = clean['LapNumber'].astype(int)

print(f"Processing {len(clean)} clean_telemetry_lap rows across {clean['Driver'].nunique()} drivers...")

rows = []
skipped = []

for _, row in clean.iterrows():
    drv, lapnum = row['Driver'], int(row['LapNumber'])
    tel_path = os.path.join(RACE_DIR, drv, f"{lapnum}_tel.json")
    if not os.path.exists(tel_path):
        skipped.append((drv, lapnum, "file not found"))
        continue
    with open(tel_path) as f:
        tel = json.load(f)['tel']

    distance = np.array(tel['distance'], dtype=float)
    if len(distance) < 10 or not np.all(np.diff(distance) >= 0):
        skipped.append((drv, lapnum, "distance not monotonic or too few points"))
        continue

    speed = np.array(tel['speed'], dtype=float)
    throttle = np.array(tel['throttle'], dtype=float)
    gear = np.array(tel['gear'], dtype=float)
    brake = np.array(tel['brake'], dtype=float)
    rpm = np.array(tel['rpm'], dtype=float)
    acc_x = np.array(tel['acc_x'], dtype=float)
    acc_y = np.array(tel['acc_y'], dtype=float)
    drs = np.array(tel['drs'], dtype=float) if tel.get('drs') is not None else np.zeros_like(distance)

    grid = np.arange(0, distance.max(), GRID_STEP)
    if len(grid) < 5:
        skipped.append((drv, lapnum, "lap too short for grid"))
        continue

    # continuous channels: linear interpolation
    speed_g = np.interp(grid, distance, speed)
    throttle_g = np.interp(grid, distance, throttle)
    rpm_g = np.interp(grid, distance, rpm)
    acc_x_g = np.interp(grid, distance, acc_x)
    acc_y_g = np.interp(grid, distance, acc_y)

    # discrete channels: step/nearest-prior interpolation (no fractional
    # gear/brake values invented)
    idx = np.searchsorted(distance, grid, side='right') - 1
    idx = np.clip(idx, 0, len(distance) - 1)
    gear_g = gear[idx]
    brake_g = brake[idx]
    drs_g = drs[idx]

    lap_df = pd.DataFrame({
        'Driver': drv,
        'LapNumber': lapnum,
        'Team': row['Team'],
        'distance': grid,
        'speed': speed_g,
        'throttle': throttle_g,
        'rpm': rpm_g,
        'gear': gear_g,
        'brake': brake_g,
        'drs': drs_g,
        'acc_x': acc_x_g,
        'acc_y': acc_y_g,
    })

    # engineered features (first differences over the spatial grid)
    lap_df['speed_delta'] = lap_df['speed'].diff().fillna(0)
    lap_df['rpm_delta'] = lap_df['rpm'].diff().fillna(0)
    lap_df['gear_delta'] = lap_df['gear'].diff().fillna(0)
    # 3-sample rolling mean of acc_x - checked on a sample lap: raw signal
    # has real high-frequency structure during braking (not just noise),
    # but a light 3-tap smoothing reduces point-to-point jitter without
    # flattening genuine braking/accel transitions. See
    # diagnostics/resample_qc_sample_lap.png for the check (note: that plot
    # was produced by an earlier ad-hoc QC pass, not regenerated by this
    # script - it's a static artifact of the original check, not
    # reproducible by re-running this file).
    lap_df['acc_x_smooth'] = lap_df['acc_x'].rolling(3, center=True, min_periods=1).mean()

    # rule-based baseline labels (sanity-check baseline, not the deliverable)
    conditions = [
        lap_df['brake'] == 1,
        lap_df['throttle'] >= 99,
    ]
    choices = ['braking', 'full_throttle']
    lap_df['rule_state'] = np.select(conditions, choices, default='partial_throttle_no_brake')

    rows.append(lap_df)

full = pd.concat(rows, ignore_index=True)
print(f"Built dataset: {len(full)} rows from {len(rows)} laps (skipped {len(skipped)})")
if skipped:
    print("Skipped:", skipped[:20])

full = full.sort_values(['Driver', 'LapNumber', 'distance']).reset_index(drop=True)
full.to_parquet(f"{PROCESSED_DIR}/resampled_telemetry.parquet", index=False)
print(f"Saved -> {PROCESSED_DIR}/resampled_telemetry.parquet")

print("\nRule-based label proportions:")
print(full['rule_state'].value_counts(normalize=True))
